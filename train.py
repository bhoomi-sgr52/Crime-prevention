"""
Sentinel Watch - YOLO Model Training and Evaluation
===================================================
This script automates the process of training a custom YOLOv8 model for weapon
detection, evaluating its performance, and deploying the best weights to the
active model directory.

Requirements:
    - ultralytics package (pip install ultralytics)
    - Dataset placed in the `dataset/` directory with `data.yaml`
"""

import os
import shutil
import argparse
from pathlib import Path

try:
    from ultralytics import YOLO
except ImportError:
    print("CRITICAL ERROR: 'ultralytics' is not installed.")
    print("Please install it by running: pip install ultralytics")
    exit(1)

def print_dataset_instructions():
    """Prints instructions on how to structure the dataset if missing."""
    print("---------------------------------------------------------")
    print(" ERROR: Dataset configuration (data.yaml) not found! ")
    print("---------------------------------------------------------")
    print("Please set up your dataset with the following exact structure in")
    print("the 'dataset' folder located in the root of the project:\n")
    print("dataset/")
    print("├── images/")
    print("│   ├── train/    (place training images here)")
    print("│   └── val/      (place validation images here)")
    print("│")
    print("├── labels/")
    print("│   ├── train/    (place training YOLO TXT labels here)")
    print("│   └── val/      (place validation YOLO TXT labels here)")
    print("│")
    print("└── data.yaml     (configuration file mapping paths and classes)\n")
    print("Example data.yaml contents:")
    print("  train: images/train")
    print("  val: images/val")
    print("  nc: 2")
    print("  names: ['weapon', 'person']")
    print("---------------------------------------------------------")

def run_training_pipeline(args):
    dataset_path = Path("dataset").resolve()
    data_yaml = dataset_path / "data.yaml"
    models_dir = Path("models").resolve()

    # 1. Check for the dataset configuration
    if not data_yaml.exists():
        print_dataset_instructions()
        return

    print("=" * 60)
    print(" Sentinel Watch - Training Pipeline Initiated")
    print("=" * 60)

    # 2. Load a pretrained YOLO model (using yolov8n as the baseline)
    print("\n[1/5] Loading pretrained YOLOv8n model...")
    model = YOLO("yolov8n.pt")

    # 3. Train on the custom dataset
    print(f"\n[2/5] Starting training on custom dataset...")
    print(f"      Epochs: {args.epochs}")
    print(f"      Image Size: {args.imgsz}")
    print(f"      Batch Size: {args.batch}")
    print(f"      Dataset: {data_yaml}\n")

    # The train method automatically splits data and evaluates per epoch
    # We set project="runs" and name="weapon_detection" to have predictable output paths
    results = model.train(
        data=str(data_yaml),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        project="runs",
        name="weapon_detection",
        exist_ok=True,         # Overwrite previous training runs with the same name
        verbose=True
    )

    # 4. Validate the model (Evaluate metrics)
    print(f"\n[3/5] Validating model performance (Conf Threshold: {args.conf})...")
    val_results = model.val(conf=args.conf)

    # Ultralytics results.results_dict contains the mAP and other metrics
    metrics = val_results.results_dict

    print("\n[4/5] Extracting Evaluation Metrics...")
    print("------------------------------------------------")
    print(f" Precision:   {metrics.get('metrics/precision(B)', 0):.4f}")
    print(f" Recall:      {metrics.get('metrics/recall(B)', 0):.4f}")
    print(f" mAP50:       {metrics.get('metrics/mAP50(B)', 0):.4f}")
    print(f" mAP50-95:    {metrics.get('metrics/mAP50-95(B)', 0):.4f}")
    print("------------------------------------------------")

    # 5. Save and copy the best trained weights to models/best.pt
    print("\n[5/5] Deploying best model weights...")
    
    # FIXED: Added the nested 'train' folder generated by Ultralytics YOLOv8
    best_weights_path = Path("runs/weapon_detection/train/weights/best.pt").resolve()
    
    if best_weights_path.exists():
        models_dir.mkdir(parents=True, exist_ok=True)
        target_path = models_dir / "best.pt"
        
        # Copy the file
        shutil.copy(str(best_weights_path), str(target_path))
        print(f"\nSUCCESS! Best model deployed to: {target_path}")
        print("Sentinel Watch will now use this model for live surveillance.")
    else:
        print(f"\nWARNING: Expected to find best weights at {best_weights_path}")
        print("but the file was missing. Deployment skipped.")

    print("=" * 60)
    print(" Training Pipeline Complete.")
    print("=" * 60)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train a custom YOLOv8 model for Sentinel Watch.")
    
    parser.add_argument("--epochs", type=int, default=50, 
                        help="Number of training epochs (default: 50)")
    parser.add_argument("--imgsz", type=int, default=640, 
                        help="Image size for training (default: 640)")
    parser.add_argument("--batch", type=int, default=16, 
                        help="Batch size (default: 16, reduce if out of memory)")
    parser.add_argument("--conf", type=float, default=0.25, 
                        help="Confidence threshold for validation evaluation (default: 0.25)")
    
    args = parser.parse_args()
    run_training_pipeline(args)